# ============================================================
# 实时数值部分（sys_config 由管理端可改，故不硬编码）
# ============================================================
# 背景：DB 现值是 points_publish=10 / points_exchange=20 / carbon=5.0，
# 但代码兜底默认是 20 / 50，两套值并不一致。把数字写死进提示词，
# 一旦管理端改配置，AI 就会与平台实际规则矛盾；故每次请求实时读取。
_DEFAULT_RULES = {
    "points_publish": 10,
    "points_exchange": 20,
    "carbon_per_exchange": 5.0,
}


def build_points_rules_block(rules: dict | None = None) -> str:
    """把实时积分规则 + 常见问答口径拼成提示词片段。

    Args:
        rules: points_service.get_effective_rules() 的返回值；
               缺字段或传 None 时逐项回落 `_DEFAULT_RULES`。
    """
    data = dict(_DEFAULT_RULES)
    if isinstance(rules, dict):
        for key in data:
            value = rules.get(key)
            if value is not None:
                data[key] = value

    publish = data["points_publish"]
    exchange = data["points_exchange"]
    # 碳减排量在 DB 里是 5.0 这类浮点，提示词里写成「5kg」比「5.0kg」自然
    carbon = data["carbon_per_exchange"]
    if isinstance(carbon, float) and carbon.is_integer():
        carbon = int(carbon)

    # 积分-现金汇率与 settings.merchant_points_to_yuan 同源联动（不写死 1 元），
    # 避免代码调汇率后提示词各说各话（与 /admin/recycle/stats 的成本口径同源）
    from app.core.config import settings as _settings

    yuan_per_100 = 100 * float(_settings.merchant_points_to_yuan)
    yuan_text = f"{yuan_per_100:g}" if yuan_per_100 == yuan_per_100 else "1"

    return (
        "\n\n【积分规则】（以下为平台当前生效的数值，回答积分问题时以此为准）"
        f"\n- 发布物品：审核通过后 +{publish} 积分（注意是**审核通过时**发放，不是刚提交时）"
        f"\n- 完成交换：交换双方各 +{exchange} 积分、各 +{carbon}kg 碳减排"
        "\n- 积分商城兑换：按商品标价扣积分"
        f"\n- 100 积分 = {yuan_text} 元：这是平台与商家/回收商之间的结算口径，用户问及时可以说明，不必主动提起"
        "\n【常见问答口径】仅在用户主动问到对应问题时使用，按此口径回答，不要编造未上线的功能："
        "\nQ：怎么用旧书换商家服务？/ 怎么用物品换积分？"
        "\nA：两种方式都行："
        "\n   **方式一（两段式）**：先把书发布到平台，交易方式选「免费送」「交换」或「低价转让」；"
        f"审核通过后 +{publish} 积分；书被邻居接手、交换完成后 +{exchange} 积分；"
        "积分累计后到「积分商城」兑换商家服务，例如 30 积分可换便利店纸巾、50 积分可换打印券。"
        "\n   **方式二（直接回收）**：发布时交易方式选「交给平台回收」，按物品成色估价，"
        "**提交后立即到账积分**（不用等成交），平台安排取件。适合想马上拿到积分的情况。"
        "\nQ：平台回收怎么估价？"
        "\nA：平台按物品成色自动估价（提交发布弹窗里能看到估价），成色越好估价越高；"
        "选「交给平台回收」并提交后积分立即到账，之后平台安排取件、再由平台出售给合作回收商。"
        "\nQ：积分怎么用？"
        "\nA：在「积分商城」里选商品，确认兑换后获得 6 位核销码，到实体店出示核销码即可核销。"
        "\nQ：有哪些商家 / 我能换到什么？"
        "\nA：调用 get_merchant_list 与 get_merchant_products 查询实时名单与商品。"
    )
